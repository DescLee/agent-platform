export type PixelPalette = Record<string, string>;

const gridArt = (source: string): string[] => {
  const rows = source.trim().split("\n").map((line) => line.trim());
  if (rows.length !== 40) throw new Error(`Pet art must contain 40 rows, got ${rows.length}`);
  return rows.map((row, index) => {
    if (row.length > 32) throw new Error(`Pet art row ${index} is ${row.length} cells wide`);
    return row.padEnd(32, ".");
  });
};

