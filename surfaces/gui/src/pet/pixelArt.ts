export const BANNER_TIRED_ART = BANNER_ART.map((row, index) => {
  if (index === 7) return row.replace(/B/g, "F");
  if (index === 8) return row.replace(/BQX/g, "FXX").replace(/QXB/g, "XXF");
  if (index === 11) return row.replace("m", "s");
  if (index === 12) return row.replace("FFFFFF", "FFmmFF");
  return row;
});

