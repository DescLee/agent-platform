export const SURGE_ART = BANNER_ART.map((row, index) => {
  if (index >= 5 && index <= 14) return row.replace(/[SsLN]/g, "G").replace(/F/g, "D");
  if (index >= 15 && index <= 24) return row.replace(/C/g, "R").replace(/c/g, "D");
  if (index >= 25 && index <= 37) return row.replace(/P/g, "G").replace(/p/g, "D");
  return row;
});
